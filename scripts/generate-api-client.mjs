// Generates resources/js/api/client.js from the OpenAPI document the Rust
// server produces (`monica openapi`), one function per operationId:
//
//   await api.createContactNote({ vault_id, contact_id }, { body: 'Hi' })
//
// The first argument holds the path and query parameters by name, the second
// the request body (an object, or FormData for uploads). Binary GET
// operations also get a URL builder in `urls` (for <img src>, downloads).
// Usage: node scripts/generate-api-client.mjs resources/js/api/openapi.json

import { readFileSync, writeFileSync } from 'node:fs';

const spec = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const out = [];
const urls = [];
const methods = ['get', 'post', 'put', 'patch', 'delete'];

out.push('// Generated by scripts/generate-api-client.mjs from openapi.json. Do not edit.');
out.push("import { request, buildUrl } from './runtime';");
out.push('');

const resolve = (p) => (p.$ref ? p.$ref.split('/').slice(1).reduce((o, k) => o[k], spec) : p);

const isBinary = (op) => {
  const ok = op.responses?.['200']?.content ?? {};
  return Object.keys(ok).some((t) => !t.includes('json'));
};

for (const [path, item] of Object.entries(spec.paths).sort()) {
  for (const method of methods) {
    const op = item[method];
    if (!op) continue;
    const id = op.operationId;
    const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map(resolve);
    const pathParams = [...path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    const queryParams = params.filter((p) => p.in === 'query').map((p) => p.name);
    const multipart = !!op.requestBody?.content?.['multipart/form-data'];
    out.push('/**');
    out.push(` * ${op.summary ?? id} (\`${method.toUpperCase()} ${path}\`).`);
    out.push(` * @param {import('./schema').operations['${id}']['parameters']['path'] & import('./schema').operations['${id}']['parameters']['query']} [params]`);
    if (op.requestBody) {
      out.push(` * @param {${multipart ? 'FormData' : `import('./schema').operations['${id}']['requestBody']['content']['application/json']`}} [body]`);
    }
    out.push(' */');
    const spec = JSON.stringify({ method: method.toUpperCase(), path, pathParams, queryParams, binary: isBinary(op) });
    out.push(`export const ${id} = (params = {}, body = undefined) => request(${spec}, params, body);`);
    out.push('');
    if (method === 'get' && isBinary(op)) {
      urls.push(`  ${id}: (params = {}) => buildUrl(${JSON.stringify({ path, pathParams, queryParams })}, params),`);
    }
  }
}
out.push('/** URLs of binary GET operations, for <img src> and downloads. */');
out.push('export const urls = {');
out.push(...urls);
out.push('};');
writeFileSync('resources/js/api/client.js', out.join('\n') + '\n');
console.log(`wrote resources/js/api/client.js`);
