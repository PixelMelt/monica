#!/usr/bin/env python3
"""Scaffold the Rust API modules from the approved draft (one-shot tool).

Usage: python3 docs/rewrite/tools/gen_api.py [--force]

For every fragment of docs/rewrite/api/ that has operations not yet in the
Rust code, writes rust/src/api/<module>.rs with:
  - one struct per component schema the fragment defines (request bodies
    Deserialize with every field optional, PATCH bodies with
    `Option<Option<T>>` for nullable fields, read models Serialize), skipping
    schemas the code already defines;
  - one handler per operation not yet implemented, with its full
    `#[utoipa::path]` annotation (path, operationId, tag, summary,
    parameters, request body, every response, x-permission, x-inventory,
    x-services), the extractors and the vault/administrator access check,
    and a `todo!()` body;
  - `routes()`, which registers the handlers.
Schemas of docs/rewrite/api/00-base.yaml go to rust/src/api/base.rs.

Existing files are left alone unless --force is given.
"""

import glob
import os
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
API = os.path.join(ROOT, "docs/rewrite/api")
SRC = os.path.join(ROOT, "rust/src/api")

MODULES = {
    "00": "base",
    "12": "reference",
    "20": "personalize",
    "21": "templates",
    "30": "contact_notes",
    "31": "contacts",
    "32": "contact_modules_a",
    "33": "contact_modules_b",
    "34": "groups",
    "40": "vault_settings",
    "41": "vault_pages",
    "50": "journals",
}
METHODS = ("get", "post", "put", "patch", "delete")
SCALAR_REFS = {"Uuid", "Id", "Timestamp", "Date"}

spec = yaml.safe_load(open(os.path.join(ROOT, "docs/rewrite/openapi.yaml")))
SCHEMAS = spec["components"]["schemas"]
PARAMS = spec["components"]["parameters"]
RESPONSES = spec["components"]["responses"]

# Which fragment defines which schema and operation.
schema_home = {}
op_home = {}
for path in sorted(glob.glob(os.path.join(API, "*.yaml"))):
    frag = os.path.basename(path)[:2]
    doc = yaml.safe_load(open(path)) or {}
    for name in (doc.get("components") or {}).get("schemas") or {}:
        schema_home[name] = frag
    for p, item in (doc.get("paths") or {}).items():
        for m in METHODS:
            if m in item:
                op_home[(p, m)] = frag

# What the code already has.
existing_structs = {}
implemented = set()
for path in glob.glob(os.path.join(SRC, "*.rs")):
    mod = os.path.basename(path)[:-3]
    text = open(path).read()
    if "// Generated by docs/rewrite/tools/gen_api.py" in text and "--force" in sys.argv:
        continue
    for name in re.findall(r"^pub (?:struct|enum) (\w+)", text, re.M):
        existing_structs.setdefault(name, mod)
    implemented |= set(re.findall(r'operation_id = "(\w+)"', text))


def deref(s):
    while isinstance(s, dict) and "$ref" in s:
        s = SCHEMAS[s["$ref"].split("/")[-1]]
    return s


def ref_name(s):
    return s["$ref"].split("/")[-1] if isinstance(s, dict) and "$ref" in s else None


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[_\W]+", s) if p)


def snake(s):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", s).lower()


def rust_field(name):
    return f"r#{name}" if name in {"type", "ref", "move", "use", "match", "loop", "self", "fn", "mod"} else name


# --- usage: which schemas are request bodies, which are read models -------

request_schemas, response_schemas = set(), set()


def collect(s, into, seen=None):
    seen = seen if seen is not None else set()
    if not isinstance(s, dict):
        return
    n = ref_name(s)
    if n:
        if n in seen:
            return
        seen.add(n)
        into.add(n)
        collect(SCHEMAS[n], into, seen)
        return
    for k in ("allOf", "oneOf", "anyOf"):
        for x in s.get(k, []):
            collect(x, into, seen)
    for v in (s.get("properties") or {}).values():
        collect(v, into, seen)
    if "items" in s:
        collect(s["items"], into, seen)


for p, item in spec["paths"].items():
    for m in METHODS:
        op = item.get(m)
        if not op:
            continue
        for c in ((op.get("requestBody") or {}).get("content") or {}).values():
            collect(c.get("schema"), request_schemas)
        for r in op["responses"].values():
            r = RESPONSES[ref_name(r)] if ref_name(r) else r
            for c in (r.get("content") or {}).values():
                collect(c.get("schema"), response_schemas)


# --- types ---------------------------------------------------------------


class Gen:
    def __init__(self, module):
        self.module = module
        self.structs = []  # (name, schema, kind)
        self.structs_by_name = {}
        self.aliases = []  # (name, schema): scalar and oneOf schemas
        self.names = set()
        self.uses = set()

    def use_schema(self, name):
        if name in SCALAR_REFS:
            return
        home = existing_structs.get(name)
        if home is None:
            frag = schema_home.get(name)
            home = MODULES.get(frag, "base") if frag else "base"
        if home != self.module:
            self.uses.add(f"super::{home}::{name}")

    def ty(self, s, owner, field, kind):
        """(rust type, utoipa value_type or None, extra schema attrs)."""
        n = ref_name(s)
        if n == "Uuid":
            self.uses.add("crate::db::uuid::Uuid")
            return "Uuid", "uuid::Uuid", ""
        if n == "Id":
            self.uses.add("crate::db::id::Id")
            return "Id", "i64", ""
        if n == "Timestamp":
            self.uses.add("crate::db::timestamp::Timestamp")
            return "Timestamp", "String", "format = DateTime"
        if n == "Date":
            self.uses.add("chrono::NaiveDate")
            return "NaiveDate", None, ""
        if n:
            target = SCHEMAS[n]
            if "oneOf" in target and not all(ref_name(x) for x in target["oneOf"]):
                pass
            self.use_schema(n)
            return n, None, ""
        if not isinstance(s, dict):
            return "serde_json::Value", "Object", ""
        for key in ("oneOf", "anyOf"):
            if key in s:
                real = [x for x in s[key] if x.get("type") != "null"]
                if len(real) == 1:
                    t, v, a = self.ty(real[0], owner, field, kind)
                    return f"Option<{t}>", (f"Option<{v}>" if v else None), a
                return "serde_json::Value", "Object", ""
        if "allOf" in s:
            if len(s["allOf"]) == 1 and not s.get("properties"):
                return self.ty(s["allOf"][0], owner, field, kind)
            name = self.fresh(owner + pascal(field), s)
            self.add_struct(name, s, kind)
            return name, None, ""
        types = s.get("type")
        types = types if isinstance(types, list) else [types]
        nullable = "null" in types
        types = [t for t in types if t != "null"]
        t = types[0] if types else None
        if "const" in s and t is None:
            t = "string"
        if t == "array":
            it, iv, ia = self.ty(s.get("items", {}), owner, singular(field), kind)
            base = (f"Vec<{it}>", f"Vec<{iv}>" if iv else None, ia)
        elif t == "object":
            if s.get("properties"):
                name = self.fresh(owner + pascal(field), s)
                self.add_struct(name, s, kind)
                base = (name, None, "")
            else:
                base = ("serde_json::Value", "Object", "")
        elif t == "string":
            fmt = s.get("format")
            if fmt == "date-time":
                base = ("String", None, "format = DateTime")
            elif fmt == "uuid":
                self.uses.add("crate::db::uuid::Uuid")
                base = ("Uuid", "uuid::Uuid", "")
            elif fmt == "date":
                self.uses.add("chrono::NaiveDate")
                base = ("NaiveDate", None, "")
            else:
                base = ("String", None, "")
        elif t == "integer":
            base = ("i32", None, "") if s.get("format") == "int32" else ("i64", None, "")
        elif t == "number":
            base = ("f64", None, "")
        elif t == "boolean":
            base = ("bool", None, "")
        else:
            base = ("serde_json::Value", "Object", "")
        if nullable:
            rt, vt, a = base
            return f"Option<{rt}>", (f"Option<{vt}>" if vt else None), a
        return base

    def fresh(self, name, schema):
        """A struct name for an inline schema that no component schema takes."""
        candidate = name
        while candidate in SCHEMAS or candidate in existing_structs or (
            candidate in self.names and dict(self.structs_by_name.get(candidate) or {}) != schema
        ):
            candidate += "Item"
        return candidate

    def add_struct(self, name, schema, kind):
        if name in self.names or (name in existing_structs and existing_structs[name] != self.module):
            return
        self.names.add(name)
        self.structs_by_name[name] = schema
        self.structs.append((name, schema, kind))

    def fields(self, schema):
        """Merged properties and required names of an object schema."""
        props, required = {}, set()
        schema = schema if "$ref" not in schema else deref(schema)
        for part in schema.get("allOf", []):
            p, r = self.fields(deref(part) if ref_name(part) else part)
            props.update(p)
            required |= r
        for key in ("oneOf", "anyOf"):
            for part in schema.get(key, []):
                part = deref(part) if ref_name(part) else part
                if part.get("type") == "null":
                    continue
                p, _ = self.fields(part)
                props.update(p)
        props.update(schema.get("properties") or {})
        required |= set(schema.get("required") or [])
        return props, required

    def render_struct(self, name, schema, kind):
        out = []
        desc = schema.get("description")
        if desc:
            out += doc(desc, "")
        derives = {"read": "Serialize, ToSchema", "body": "Deserialize, ToSchema", "both": "Serialize, Deserialize, ToSchema"}[kind]
        out.append(f"#[derive({derives})]")
        props, required = self.fields(schema)
        patch = kind == "body" and name.endswith("Update")
        out.append(f"pub struct {name} {{")
        if not props:
            out.append("}")
            return out
        for field, fs in props.items():
            if field_doc := (fs.get("description") if isinstance(fs, dict) else None):
                out += doc(field_doc, "    ")
            rt, vt, extra = self.ty(fs, name, field, kind)
            attrs = []
            if kind == "body":
                inner = rt[7:-1] if rt.startswith("Option<") else rt
                inner_v = (vt[7:-1] if vt and vt.startswith("Option<") else vt)
                if patch and rt.startswith("Option<"):
                    rt = f"Option<Option<{inner}>>"
                    vt = f"Option<{inner_v or inner}>"
                    attrs.append('#[serde(default, with = "::serde_with::rust::double_option")]')
                else:
                    rt = f"Option<{inner}>"
                    vt = f"Option<{inner_v}>" if inner_v else None
            elif field not in required and not rt.startswith("Option<"):
                rt = f"Option<{rt}>"
                vt = f"Option<{vt}>" if vt else None
                attrs.append('#[serde(skip_serializing_if = "Option::is_none")]')
            schema_attr = ", ".join(x for x in [f"value_type = {vt}" if vt else "", extra] if x)
            if schema_attr:
                attrs.append(f"#[schema({schema_attr})]")
            if kind != "body" and field == "type":
                pass
            rname = snake(re.sub(r"\W", "_", field))
            if rname != field:
                attrs.insert(0, f'#[serde(rename = "{field}")]')
            for a in attrs:
                out.append(f"    {a}")
            out.append(f"    pub {rust_field(rname)}: {rt},")
        out.append("}")
        return out


def singular(field):
    return field[:-3] + "y" if field.endswith("ies") else field[:-1] if field.endswith("s") else field + "Item"


def doc(text, indent):
    lines = []
    for para in str(text).strip().split("\n"):
        lines.append(f"{indent}/// {para}".rstrip())
    return lines


# --- operations ----------------------------------------------------------

ACCESS = {
    "vault:view": "View",
    "vault:edit": "Edit",
    "vault:manage": "Manage",
}


def param(p):
    return PARAMS[ref_name(p)] if ref_name(p) else p


def render_op(g, path, method, op, item):
    oid = op["operationId"]
    fn = snake(oid)
    params = [param(p) for p in item.get("parameters", []) + op.get("parameters", [])]
    path_params = [p for p in params if p["in"] == "path"]
    query_params = [p for p in params if p["in"] == "query"]
    header_params = [p for p in params if p["in"] == "header"]
    path_params.sort(key=lambda p: path.index("{" + p["name"] + "}"))

    attr = [f"    {method},", f'    path = "{path}",', f'    operation_id = "{oid}",', f'    tag = "{op["tags"][0]}",']
    if op.get("summary"):
        attr.append(f"    summary = {rust_str(op['summary'])},")
    plist = []
    for p in path_params:
        t, v, _ = g.ty(p["schema"], pascal(oid), p["name"], "body")
        plist.append(f'("{p["name"]}" = {v or t}, Path)')
    query_struct = None
    if query_params:
        query_struct = pascal(oid) + "Query"
        plist.append(query_struct)
    for p in header_params:
        plist.append(f'("{p["name"]}" = Option<String>, Header)')
    if plist:
        attr.append(f"    params({', '.join(plist)}),")
    body = op.get("requestBody")
    body_kind = None
    if body:
        content = body["content"]
        ctype, c = next(iter(content.items()))
        n = ref_name(c.get("schema"))
        if "multipart" in ctype:
            body_kind = "multipart"
            g.use_schema(n or "FileUpload")
            attr.append(f'    request_body(content_type = "multipart/form-data", content = {n or "FileUpload"}),')
        else:
            if n is None:
                n = pascal(oid) + "Body"
                g.add_struct(n, c.get("schema") or {}, "body")
            else:
                g.use_schema(n)
            body_kind = n
            attr.append(f"    request_body = {n},")
    resp = []
    success = None
    for code, r in op["responses"].items():
        r = RESPONSES[ref_name(r)] if ref_name(r) else r
        d = rust_str(r.get("description", ""))
        content = r.get("content") or {}
        json_c = next((c for t, c in content.items() if "json" in t), None)
        if json_c is not None and ref_name(json_c.get("schema")) and code.startswith("2"):
            n = ref_name(json_c["schema"])
            g.use_schema(n)
            resp.append(f"(status = {code}, description = {d}, body = {n})")
            success = success or (code, n)
        elif content and code.startswith("2") and json_c is None:
            t = next(iter(content))
            resp.append(f'(status = {code}, description = {d}, content_type = "{t}")')
            success = success or (code, "binary")
        else:
            resp.append(f"(status = {code}, description = {d})")
            if code.startswith("2"):
                success = success or (code, None)
    attr.append("    responses(" + ", ".join(resp) + "),")
    ext = [
        f'("x-permission" = json!("{op["x-permission"]}"))',
        f'("x-inventory" = json!({yaml_list(op.get("x-inventory", []))}))',
        f'("x-services" = json!({yaml_list(op.get("x-services", []))}))',
    ]
    attr.append(f"    extensions({', '.join(ext)})")
    out = []
    if query_struct:
        out.append("#[derive(Debug, Default, Deserialize, IntoParams)]")
        out.append("#[into_params(parameter_in = Query)]")
        out.append(f"pub struct {query_struct} {{")
        for p in query_params:
            if p.get("description"):
                out += doc(p["description"], "    ")
            t, v, a = g.ty(p.get("schema", {}), query_struct, p["name"], "body")
            inner = t[7:-1] if t.startswith("Option<") else t
            inner_v = v[7:-1] if v and v.startswith("Option<") else v
            if inner_v:
                out.append(f"    #[param(value_type = Option<{inner_v}>)]")
            out.append(f"    pub {rust_field(p['name'])}: Option<{inner}>,")
        out.append("}")
        out.append("")
    out.append("#[utoipa::path(")
    out += attr
    out.append(")]")
    args = ["State(state): State<AppState>"]
    perm = op["x-permission"]
    if perm != "public":
        args.append("Auth(id): Auth")
    if path_params:
        names = [p["name"] for p in path_params]
        types = []
        for p in path_params:
            t, _, _ = g.ty(p["schema"], pascal(oid), p["name"], "body")
            types.append(t)
        if len(names) == 1:
            args.append(f"Path({names[0]}): Path<{types[0]}>")
        else:
            args.append(f"Path(({', '.join(names)})): Path<({', '.join(types)})>")
    if query_struct:
        args.append(f"Query(query): Query<{query_struct}>")
    if header_params:
        args.append("headers: HeaderMap")
    if body_kind == "multipart":
        args.append("multipart: Multipart")
    elif body_kind:
        args.append(f"Json(body): Json<{body_kind}>")
    code, ret = success or ("204", None)
    if ret == "binary":
        rtype = "ApiResult<Response>"
    elif ret:
        rtype = f"ApiResult<Json<{ret}>>" if code == "200" else f"ApiResult<(StatusCode, Json<{ret}>)>"
    else:
        rtype = "ApiResult<StatusCode>"
    out.append(f"pub async fn {fn}(")
    for a in args:
        out.append(f"    {a},")
    out.append(f") -> {rtype} {{")
    if perm in ACCESS:
        out.append(
            f"    let access = access::vault(&state, &id, vault_id, crate::domains::base::VaultPermission::{ACCESS[perm]}).await?;"
        )
    elif perm == "account:admin":
        out.append("    access::administrator(&id)?;")
    out.append(f'    todo!("{oid}")')
    out.append("}")
    return fn, out


def rust_str(s):
    return '"' + str(s).strip().replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def yaml_list(xs):
    return "[" + ", ".join(f'"{x}"' for x in xs) + "]"


# --- files ---------------------------------------------------------------


def generate(frag, module):
    g = Gen(module)
    for name, frag_of in schema_home.items():
        if frag_of != frag or name in SCALAR_REFS or name in existing_structs:
            continue
        s = SCHEMAS[name]
        if (s.get("type") not in (None, "object") and "allOf" not in s) or ("oneOf" in s and not s.get("properties")):
            g.aliases.append((name, s))
            continue
        kind = "both" if name in request_schemas and name in response_schemas else "body" if name in request_schemas else "read"
        g.add_struct(name, s, kind)
    ops = []
    for (p, m), f in op_home.items():
        if f != frag:
            continue
        op = spec["paths"][p][m]
        if op["operationId"] in implemented:
            continue
        ops.append((p, m, op, spec["paths"][p]))
    if not g.structs and not ops and not g.aliases:
        return None
    rendered = []
    for name, sch in g.aliases:
        lines = doc(sch["description"], "") if sch.get("description") else []
        if "oneOf" in sch:
            lines.append("// TODO(endpoints): hand-written: a oneOf of the variants in the draft.")
            lines.append(f"pub type {name} = serde_json::Value;")
        else:
            t, _, _ = g.ty({k: v for k, v in sch.items() if k != "description"}, name, "", "read")
            lines.append(f"pub type {name} = {t};")
        rendered.append(lines)
    i = 0
    while i < len(g.structs):
        rendered.append(g.render_struct(*g.structs[i]))
        i += 1
    handlers = []
    for p, m, op, item in ops:
        handlers.append((p, *render_op(g, p, m, op, item)))
    # structs added while rendering handlers (inline query/param objects)
    while i < len(g.structs):
        rendered.append(g.render_struct(*g.structs[i]))
        i += 1
    text = []
    text.append(f"//! `/api/v1` operations of `docs/rewrite/api/{os.path.basename(glob.glob(os.path.join(API, frag + '-*.yaml'))[0])}`.")
    text.append("// Generated by docs/rewrite/tools/gen_api.py; the handlers are filled in by hand.")
    text.append("")
    body = "\n".join("\n".join(r) + "\n" for r in rendered)
    hbody = "\n".join("\n".join(h[2]) + "\n" for h in handlers)
    uses = set(g.uses)
    all_text = body + hbody
    if "Serialize" in all_text or "Deserialize" in all_text:
        derives = [d for d in ("Deserialize", "Serialize") if re.search(rf"\b{d}\b", all_text)]
        uses.add("serde::{" + ", ".join(derives) + "}" if len(derives) > 1 else f"serde::{derives[0]}")
    if "ToSchema" in all_text and "IntoParams" in all_text:
        uses.add("utoipa::{IntoParams, ToSchema}")
    elif "ToSchema" in all_text:
        uses.add("utoipa::ToSchema")
    elif "IntoParams" in all_text:
        uses.add("utoipa::IntoParams")
    if handlers:
        uses |= {"crate::http::state::AppState", "crate::error::ApiResult", "axum::extract::State"}
        uses.add("utoipa_axum::router::OpenApiRouter")
        uses.add("utoipa_axum::routes")
        if "Auth(id)" in hbody:
            uses.add("crate::http::auth::Auth")
        if "access::" in hbody:
            uses.add("crate::http::access")
        if "Path(" in hbody:
            uses.add("axum::extract::Path")
        if "Query(" in hbody:
            uses.add("axum::extract::Query")
        if "Json<" in hbody:
            uses.add("crate::http::json::Json")
        if "StatusCode" in hbody:
            uses.add("axum::http::StatusCode")
        if "HeaderMap" in hbody:
            uses.add("axum::http::HeaderMap")
        if "Multipart" in hbody:
            uses.add("axum::extract::Multipart")
        if "Response>" in hbody:
            uses.add("axum::response::Response")
    for u in sorted(uses, key=lambda u: (not u.startswith(("std", "axum", "chrono", "serde", "utoipa")), u)):
        text.append(f"use {u};")
    text.append("")
    text.append(body)
    text.append(hbody)
    if handlers:
        by_path = {}
        for p, fn, _ in handlers:
            by_path.setdefault(p, []).append(fn)
        text.append("/// The operations of this module.")
        text.append("pub fn routes() -> OpenApiRouter<AppState> {")
        text.append("    OpenApiRouter::new()")
        for p, fns in by_path.items():
            text.append(f"        .routes(routes!({', '.join(fns)}))")
        text.append("}")
    return "\n".join(text) + "\n"


def main():
    force = "--force" in sys.argv
    for frag, module in MODULES.items():
        out = generate(frag, module)
        if out is None:
            continue
        path = os.path.join(SRC, f"{module}.rs")
        if os.path.exists(path) and not force:
            print(f"skip {path} (exists)")
            continue
        open(path, "w").write(out)
        print(f"wrote {path}")


main()
